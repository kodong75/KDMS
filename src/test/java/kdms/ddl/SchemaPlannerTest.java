    @Test
    void NULL_허용_UNIQUE_는_NULLS_NOT_DISTINCT_필터_인덱스는_WHERE() {
        SourceCatalog.Column code = KdmsMockCatalog.col(2, "code", "int", 4, 10, 0, true);
        SourceCatalog.Column email = KdmsMockCatalog.text(3, "email", "varchar", 100, true);
        SourceCatalog.Table t = KdmsMockCatalog.table("u", 0,
                List.of(KdmsMockCatalog.col(1, "id", "int", 4, 10, 0, false), code, email),
                List.of(KdmsMockCatalog.pk("pk_u", "id"),
                        new SourceCatalog.Index("uq_code", SourceCatalog.IndexKind.UNIQUE_CONSTRAINT, 2, "NONCLUSTERED", false, null,
                                List.of(new SourceCatalog.IndexColumn("code", false)), List.of()),
                        new SourceCatalog.Index("ux_email", SourceCatalog.IndexKind.UNIQUE_INDEX, 2, "NONCLUSTERED", false,
                                "([email] IS NOT NULL)", List.of(new SourceCatalog.IndexColumn("email", false)), List.of())),
                List.of(), List.of());
        SchemaPlan p = SchemaPlanner.plan(new SourceCatalog("X", KdmsMockCatalog.CI, List.of(t), List.of(), List.of()), ALL,
                RulesLoader.load(null), null);
        assertThat(DdlWriter.write(p, DdlWriter.Phase.POST_LOAD))
                .contains("ALTER TABLE \"dbo\".\"u\" ADD CONSTRAINT \"uq_code\" UNIQUE NULLS NOT DISTINCT (\"code\")")
                .contains("CREATE UNIQUE INDEX \"ux_email\" ON \"dbo\".\"u\" (lower(\"email\")) WHERE (\"email\" IS NOT NULL)");
    }

    @Test
    void 필터_조건은_단순한_것만_옮긴다() {
        Map<String, String> cols = Map.of("a", "a", "b", "b_new");
        assertThat(SchemaPlanner.translateFilter("([a] IS NOT NULL AND [b]>(0))", cols)).isEqualTo("(\"a\" IS NOT NULL AND \"b_new\">(0))");
        assertThat(SchemaPlanner.translateFilter("([a]=N'Y')", cols)).isEqualTo("(\"a\"='Y')");
        assertThat(SchemaPlanner.translateFilter("([a]>getdate())", cols)).isNull();
        assertThat(SchemaPlanner.translateFilter("([zz] IS NULL)", cols)).isNull();
    }

