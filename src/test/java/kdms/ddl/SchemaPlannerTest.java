    @Test
    void 데이터_검사_결과_NUL_은_fail_규칙이면_오류() {
        Map<String, SourceDataScanner.TableScan> scan = Map.of("dbo.research_doc", new SourceDataScanner.TableScan(10,
                Map.of("body", new SourceDataScanner.ColumnScan(2, 0), "pub_dtm", new SourceDataScanner.ColumnScan(0, 3))));
        SchemaPlan p = SchemaPlanner.plan(KdmsMockCatalog.catalog(), ALL, RulesLoader.load(Path.of("config/kdms-rules.yml")), scan);
        assertThat(p.blocked()).isTrue();
        assertThat(p.allIssues()).anyMatch(i -> i.level() == Issue.Level.ERROR && i.where().equals("dbo.research_doc.body")
                && i.message().contains("NUL 문자가 든 행 2건"));
        assertThat(p.allIssues()).anyMatch(i -> i.level() == Issue.Level.NOTE && i.message().contains("센티널 날짜 행 3건"));
    }

