    @Test
    void 스키마_이름_바꾸기와_규칙_오타_경고() throws Exception {
        Path f = java.nio.file.Files.createTempFile("rules", ".yml");
        java.nio.file.Files.writeString(f, """
                identifiers:
                  schemas: { dbo: mock }
                  map: { dbo.app_user: users }
                computed_columns: { action: value_with_warning }
                tables:
                  dbo.no_such: { exclude: true }
                  dbo.issuer:
                    columns:
                      no_such_col: { trailing_space: rtrim }
                      issuer_nm: { name: issuer_name }
                """);
        SchemaPlan p = SchemaPlanner.plan(KdmsMockCatalog.catalog(), ALL, RulesLoader.load(f), null);
        String pre = DdlWriter.write(p, DdlWriter.Phase.PRE_LOAD);
        assertThat(pre).contains("CREATE TABLE \"mock\".\"users\"").contains("\"issuer_name\" varchar(100)")
                .contains("nextval('\"mock\".\"seq_doc_no\"'::regclass)");
        assertThat(DdlWriter.write(p, DdlWriter.Phase.POST_LOAD)).contains("ON \"mock\".\"issuer\" (\"issuer_name\")");
        assertThat(p.allIssues()).extracting(Issue::where).contains("규칙 tables.dbo.no_such", "규칙 tables.dbo.issuer.columns.no_such_col");
        java.nio.file.Files.delete(f);
    }

    @Test
    void 규칙_없는_타입_긴_이름_모르는_기본값은_오류() {
        SourceCatalog.Column geo = KdmsMockCatalog.col(2, "loc", "geography", -1, 0, 0, true);
        SourceCatalog.Column longName = KdmsMockCatalog.col(3, "c".repeat(64), "int", 4, 10, 0, true);
        SourceCatalog.Column odd = KdmsMockCatalog.withDefault(KdmsMockCatalog.col(4, "d", "int", 4, 10, 0, true), "df_d", "(abs(-1))");
        SourceCatalog.Table t = KdmsMockCatalog.table("odd", 0,
                List.of(KdmsMockCatalog.col(1, "id", "int", 4, 10, 0, false), geo, longName, odd),
                List.of(KdmsMockCatalog.pk("pk_odd", "id")), List.of(), List.of());
        SourceCatalog cat = new SourceCatalog("X", KdmsMockCatalog.CI, List.of(t), List.of(), List.of());
        SchemaPlan p = SchemaPlanner.plan(cat, ALL, RulesLoader.load(null), null);
        assertThat(p.allIssues()).filteredOn(i -> i.level() == Issue.Level.ERROR).extracting(Issue::message)
                .anySatisfy(m -> assertThat(m).contains("타입 규칙 없음: geography"))
                .anySatisfy(m -> assertThat(m).contains("63바이트"))
                .anySatisfy(m -> assertThat(m).contains("자동으로 옮기지 않는 식: (abs(-1))"));
    }

