    /**
     * 2단계 완료 기준(plan.md §6): KIS sql/20_pg/gen/mock.sql(2026-09-30 생성)의 테이블 정의와 같은 타입.
     * 아래 값은 그 파일에서 그대로 옮겼다. file_attach 는 mock.sql 생성 뒤 KIS #23 이 더한 테이블이라
     * KIS sql/10_mssql/20_gen_pg_ddl.sql 의 같은 타입 규칙으로 손으로 계산했다.
     */
    @Test
    void KDMS_MOCK_대상_타입은_KIS_mock_sql_과_같다() {
        Map<String, String> kis = new LinkedHashMap<>();
        kis.put("app_user", "user_id integer, login_id varchar(30), user_nm varchar(50), email varchar(100), member_level smallint, joined_dtm timestamp(3)");
        kis.put("code_master", "code_grp varchar(20), code varchar(10), code_nm varchar(100), code_nm_short varchar(20), sort_no smallint, use_yn char(1)");
        kis.put("daily_count", "snap_dt date, table_nm varchar(128), row_cnt bigint");
        kis.put("file_attach", "file_id integer, case_cd varchar(10), case_desc varchar(200), file_nm varchar(260), file_nm_a varchar(260), "
                + "file_path varchar(400), file_url varchar(2000)");
        kis.put("issuer", "issuer_id integer, issuer_cd char(6), issuer_nm varchar(100), issuer_nm_cp949 varchar(40), issuer_nm_en varchar(200), "
                + "region_cd char(2), industry_cd varchar(2), is_listed boolean, issuer_guid uuid, row_ver bytea, reg_dtm timestamp(3), upd_dtm timestamp(6)");
        kis.put("rating", "rating_id bigint, issuer_id integer, rating_cd varchar(10), outlook_cd char(1), rating_dt date, eff_dtm timestamp(3), "
                + "issue_amt numeric(19,4), coupon_rate numeric(9,4), is_watch boolean, rating_rank integer");
        kis.put("rating_hist", "hist_id bigint, rating_id bigint, action_cd char(1), old_rating_cd varchar(10), new_rating_cd varchar(10), "
                + "changed_by varchar(128), changed_dtm timestamp(3)");
        kis.put("research_doc", "doc_id integer, doc_no bigint, doc_type_cd varchar(2), issuer_id integer, title varchar(400), file_nm varchar(100), "
                + "file_path varchar(400), file_ext varchar(200), pub_dtm timestamp(3), body text, view_cnt integer");

        SchemaPlan p = mockPlan();
        Map<String, String> ours = new LinkedHashMap<>();
        for (TablePlan t : p.tables()) {
            ours.put(t.tgtName(), String.join(", ", t.columns().stream().map(c -> c.tgtName() + " " + c.tgtType()).toList()));
        }
        assertThat(ours).isEqualTo(kis);
    }

    @Test
    void KDMS_MOCK_은_오류없이_통과하고_규칙_결정이_DDL_에_보인다() {
        SchemaPlan p = mockPlan();
        assertThat(p.allIssues().stream().filter(i -> i.level() == Issue.Level.ERROR)).isEmpty();
        assertThat(p.blocked()).isFalse();

        String pre = DdlWriter.write(p, DdlWriter.Phase.PRE_LOAD);
        assertThat(pre)
                .contains("CREATE SCHEMA IF NOT EXISTS \"dbo\"")
                .contains("CREATE SEQUENCE \"dbo\".\"seq_doc_no\" AS bigint START WITH 202600001 INCREMENT BY 1 "
                        + "MINVALUE -9223372036854775808 MAXVALUE 9223372036854775807 NO CYCLE")
                .contains("\"user_id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL")
                .contains("\"login_id\" varchar(30) COLLATE \"C\" NOT NULL")
                .contains("\"member_level\" smallint DEFAULT 0 NOT NULL CHECK (\"member_level\" BETWEEN 0 AND 255)")  // tinyint
                .contains("\"joined_dtm\" timestamp(3) DEFAULT LOCALTIMESTAMP NOT NULL")                              // getdate()
                .contains("\"use_yn\" char(1) COLLATE \"C\" DEFAULT 'Y' NOT NULL")
                .contains("\"is_listed\" boolean DEFAULT false NOT NULL")                                             // ((0)) → false
                .contains("\"issuer_guid\" uuid DEFAULT gen_random_uuid() NOT NULL")                                  // newsequentialid()
                .contains("\"changed_by\" varchar(128) COLLATE \"C\" DEFAULT session_user NOT NULL")                  // suser_sname()
                .contains("\"doc_no\" bigint DEFAULT nextval('\"dbo\".\"seq_doc_no\"'::regclass) NOT NULL")           // B13
                .contains("\"rating_rank\" integer GENERATED ALWAYS AS (CASE upper(rtrim(rating_cd)) WHEN 'AAA' THEN 1")  // B12
                .contains("\"file_ext\" varchar(200) COLLATE \"C\" GENERATED ALWAYS AS (CASE WHEN strpos(file_nm, '.') > 0")
                .contains("CONSTRAINT \"pk_code_master\" PRIMARY KEY (\"code_grp\", \"code\")")
                .contains("COMMENT ON COLUMN \"dbo\".\"rating\".\"rating_rank\" IS 'MS-SQL 계산 컬럼 원문: (case rtrim([rating_cd]) when ''AAA''")
                .doesNotContain("FOREIGN KEY")
                .doesNotContain("INDEX");

        String post = DdlWriter.write(p, DdlWriter.Phase.POST_LOAD);
        assertThat(post)
                .contains("CREATE UNIQUE INDEX \"uq_app_user_login\" ON \"dbo\".\"app_user\" (lower(\"login_id\"))")  // B14
                .contains("CREATE UNIQUE INDEX \"uq_issuer_cd\" ON \"dbo\".\"issuer\" (lower(\"issuer_cd\"))")
                .contains("CREATE UNIQUE INDEX \"pk_code_master_ci\" ON \"dbo\".\"code_master\" (lower(\"code_grp\"), lower(\"code\"))")
                .contains("CREATE UNIQUE INDEX \"pk_daily_count_ci\" ON \"dbo\".\"daily_count\" (\"snap_dt\", lower(\"table_nm\"))")
                .contains("CREATE INDEX \"ix_rating_issuer_dt\" ON \"dbo\".\"rating\" (\"issuer_id\", \"rating_dt\")")
                .contains("CREATE INDEX \"ix_issuer_nm\" ON \"dbo\".\"issuer\" (\"issuer_nm\")");

        String cut = DdlWriter.write(p, DdlWriter.Phase.CUTOVER);
        assertThat(cut)
                .contains("ALTER TABLE \"dbo\".\"rating\" ADD CONSTRAINT \"fk_rating_issuer\" FOREIGN KEY (\"issuer_id\") "
                        + "REFERENCES \"dbo\".\"issuer\" (\"issuer_id\")")
                .contains("\"fk_doc_issuer\"");

        TablePlan rating = p.tables().stream().filter(t -> t.tgtName().equals("rating")).findFirst().orElseThrow();
        assertThat(rating.loadColumns()).extracting(SchemaPlan.ColumnPlan::tgtName).doesNotContain("rating_rank").hasSize(9);
    }

    @Test
    void 경고와_주의가_KIS_함정을_짚는다() {
        SchemaPlan p = mockPlan();
        String warns = String.join("\n", p.allIssues().stream().filter(i -> i.level() == Issue.Level.WARN).map(Issue::toString).toList());
        assertThat(warns)
                .contains("트리거 trg_rating_audit")                 // B11
                .contains("uniqueidentifier → uuid")
                .contains("rowversion → bytea")
                .contains("newsequentialid")
                .contains("getdate")
                .contains("자동 변환하지 않는 객체 6개");
        String notes = String.join("\n", p.allIssues().stream().filter(i -> i.level() == Issue.Level.NOTE).map(Issue::message).toList());
        assertThat(notes).contains("B01").contains("B02").contains("A03");

        SchemaPlan.ColumnPlan upd = p.tables().stream().filter(t -> t.tgtName().equals("issuer")).findFirst().orElseThrow()
                .columns().stream().filter(c -> c.srcName().equals("upd_dtm")).findFirst().orElseThrow();
        assertThat(upd.value().round()).isEqualTo("half_up");                // A06
        assertThat(upd.value().sentinel()).isEqualTo("keep");                // A08
    }

